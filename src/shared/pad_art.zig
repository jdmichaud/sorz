//! The controller overlay's pad (DESIGN.md 10.8): pixel art the port made from a photo of the Mega
//! Drive control pad, not from the game's data. The photo cut out of its white ground, shrunk to
//! pixel size, its colours snapped to the console's 8 levels (greys for the plastic, reds for its
//! marks), outlined in black as the game's sprites are; crisp red letters A, B, C drawn in its
//! buttons (the photo's shrink to dots). Each pixel a press lights is marked with its button, and
//! each colour has its pressed colour: a grey the yellow of its shade, a red the yellow of its
//! light, a letter dark red (the look the user chose, 2026-11-08). Made by tools/pad_art.py from
//! the photo (which the repository does not keep), and kept here as the port's own art: `large`
//! for one or two players, `small` (made the same way, narrower) for three or four.
//!
//! A pixel's character in `*_rows`: `.` none, else its colour's index in `palette`, `1` to `9`
//! then `a` to `z` (10 to 35). In `*_parts`: `.` none, else the button whose press lights it
//! (`u`, `d`, `l`, `r` the D-pad's arms, `a`, `b`, `c`, `s` START).
